#!/usr/bin/env python3
"""Render dataset/routing.json into `claude plugin eval` case files.

    python3 runner/gen_plugin_eval.py            # write evals/routing/**/case.yaml
    python3 runner/gen_plugin_eval.py --check    # fail if the tree is out of date

A probe removed or renamed in the JSON has its rendered case REMOVED here, and
--check fails on an orphan rather than reporting the tree up to date: a left-over
case keeps asserting a routing claim the dataset has withdrawn.

dataset/routing.json is the source of truth: the prompts and the skill each
must (or must not) route to are curated there, reviewed there, and rendered
from there. Editing a generated case.yaml by hand loses the edit on the next
run — change the JSON instead.

IMPORTANT — the grader schema below is authored from `claude plugin eval
--help` on Claude Code 2.1.263, NOT from a validated run: `plugin eval` is
early access and was not enabled on the account this dataset was built with, so
no case here has ever been executed. Treat the YAML shape as a first draft to
confirm the day early access lands (`claude plugin eval --case route-code
--runs 1`), and fix it here rather than in the generated files.
"""

import argparse
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
ROUTING = os.path.join(REPO_ROOT, "dataset", "routing.json")
EVALS = os.path.join(REPO_ROOT, "evals", "routing")

HEADER = ("# GENERATED by runner/gen_plugin_eval.py from dataset/routing.json.\n"
          "# Edit the JSON, not this file.\n")


def block(text, indent="  "):
    return "\n".join(indent + line if line else "" for line in text.splitlines())


def renderable(probe):
    """Controls test the instrument, not the plugin; they have no tier-2 case.

    `claude plugin eval` grades whether a skill fired, and a control's answer
    is known in advance (a canary registers, a missing command does not, a
    poem routes nowhere) — rendering one would only test the grader.
    """
    return probe.get("kind") != "control"


def render(probe):
    """One case.yaml body for a routing probe."""
    skill = probe["skill"]
    positive = probe["must_route"]
    lines = [HEADER,
             "name: %s" % probe["id"].lower(),
             "description: >-",
             block("%s must %sroute to %s."
                   % ("This request" if positive else "This request",
                      "" if positive else "NOT ", skill)),
             "tags:",
             "  - routing",
             "  - acs",
             "  - %s" % ("positive" if positive else "negative"),
             "runs: 3",
             "# Routing is decided in the first turn or two; a higher ceiling only",
             "# pays for the skill body to run, which this case does not assert on.",
             "max_turns: 2",
             "prompt: |",
             block(probe["prompt"]),
             "graders:"]
    if positive:
        lines += ["  - name: routes-to-%s" % skill.replace(":", "-"),
                  "    tool_used: Skill",
                  "    skill: %s" % skill]
    else:
        lines += ["  - name: does-not-route-to-%s" % skill.replace(":", "-"),
                  "    tool_not_used: Skill",
                  "    skill: %s" % skill,
                  "  # %s" % probe["why"]]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any generated file is missing or stale")
    args = ap.parse_args()

    with open(ROUTING) as fh:
        routing = json.load(fh)

    stale, written, expected = [], 0, set()
    for probe in routing["probes"]:
        if not renderable(probe):
            continue
        path = os.path.join(EVALS, probe["id"].lower(), "case.yaml")
        expected.add(probe["id"].lower())
        body = render(probe)
        current = None
        if os.path.isfile(path):
            with open(path) as fh:
                current = fh.read()
        if current == body:
            continue
        if args.check:
            stale.append(os.path.relpath(path, REPO_ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(body)
        written += 1

    orphans = []
    if os.path.isdir(EVALS):
        for name in sorted(os.listdir(EVALS)):
            if not os.path.isdir(os.path.join(EVALS, name)) or name in expected:
                continue
            orphans.append(name)
            if not args.check:
                shutil.rmtree(os.path.join(EVALS, name))

    if args.check:
        if orphans:
            print("orphaned — these have no probe in dataset/routing.json; "
                  "re-run runner/gen_plugin_eval.py to remove them:", file=sys.stderr)
            for name in orphans:
                print("  %s" % os.path.relpath(os.path.join(EVALS, name), REPO_ROOT),
                      file=sys.stderr)
            return 1
        if stale:
            print("out of date — re-run runner/gen_plugin_eval.py:", file=sys.stderr)
            for path in stale:
                print("  %s" % path, file=sys.stderr)
            return 1
        print("evals/routing is up to date with dataset/routing.json "
              "(%d probes)" % len(routing["probes"]))
        return 0

    print("rendered %d probe(s), %d file(s) changed, %d orphan(s) removed, into %s"
          % (len(routing["probes"]), written, len(orphans),
             os.path.relpath(EVALS, REPO_ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
